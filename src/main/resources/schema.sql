CREATE TABLE IF NOT EXISTS campaigns (
 id VARCHAR(80) PRIMARY KEY, name VARCHAR(160) NOT NULL, channel VARCHAR(30) NOT NULL,
 budget DOUBLE PRECISION NOT NULL, spend DOUBLE PRECISION NOT NULL,
 impressions BIGINT NOT NULL, clicks BIGINT NOT NULL, conversions BIGINT NOT NULL,
 revenue DOUBLE PRECISION NOT NULL, risk DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS historical_logs (
 id BIGINT PRIMARY KEY, campaign_id VARCHAR(80) NOT NULL, content VARCHAR(2000) NOT NULL,
 features TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS workflows (
 id VARCHAR(36) PRIMARY KEY, campaign_id VARCHAR(80) NOT NULL REFERENCES campaigns(id),
 idempotency_key VARCHAR(120) NOT NULL UNIQUE, status VARCHAR(20) NOT NULL,
 attempts INTEGER NOT NULL DEFAULT 0, owner VARCHAR(36), lease_until BIGINT,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, error VARCHAR(1000), result TEXT
);
CREATE INDEX IF NOT EXISTS workflows_status_lease ON workflows(status, lease_until);
CREATE TABLE IF NOT EXISTS decisions (
 workflow_id VARCHAR(36) NOT NULL REFERENCES workflows(id), skill VARCHAR(40) NOT NULL,
 action VARCHAR(30) NOT NULL, reason VARCHAR(2000) NOT NULL, evidence TEXT NOT NULL,
 created_at BIGINT NOT NULL, PRIMARY KEY(workflow_id, skill)
);
CREATE TABLE IF NOT EXISTS workflow_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workflow_id VARCHAR(36) NOT NULL REFERENCES workflows(id),
 event_type VARCHAR(30) NOT NULL, attempt INTEGER NOT NULL, detail VARCHAR(1000) NOT NULL,
 created_at BIGINT NOT NULL
);
